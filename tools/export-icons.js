// Exports the hermit crab sprite as: menubar frames (Swift), favicon SVG, and a 1024 icon SVG.
'use strict';
const fs = require('fs');
const path = require('path');
global.window = {};
require(path.join(__dirname, '../public/critter.js'));
const C = global.window.Critter;

const poses = ['idle', 'type', 'ask', 'nap'];
const out = {};
for (const p of poses) out[p] = C.frames(p, 'spiral').map((g) => g.map((r) => r.join('')));
// menubar: everything solid except eye whites / highlights become holes
const mb = {};
for (const p of poses) mb[p] = out[p].map((f) => f.map((r) => r.replace(/[wUh]/g, '.').replace(/[^.]/g, '#')));
fs.writeFileSync(path.join(__dirname, '../menubar/Frames.swift'),
  '// generated by tools/export-icons.js\nlet FRAMES: [String: [[String]]] = ' +
  JSON.stringify(mb, null, 1).replace(/\{/g, '[').replace(/\}/g, ']') + '\n');

const hue = 330;
const pal = C.palette(hue);
const crab = C.rects(out.idle[0].map((r) => r.split('')), pal);
fs.writeFileSync(path.join(__dirname, '../public/icon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-4 -5 32 32" shape-rendering="crispEdges"><rect x="-4" y="-5" width="32" height="32" rx="7" fill="#1a1428"/>${crab}</svg>\n`);
console.log('ok', Object.keys(mb));
